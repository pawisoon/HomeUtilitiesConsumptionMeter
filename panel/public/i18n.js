/** Polish counts three ways, English two. */
const PLURALS = {
  pl: {
    person: (n) => (n === 1 ? "osoba" : plFew(n) ? "osoby" : "osób"),
    litre: (n) => (n === 1 ? "litr" : plFew(n) ? "litry" : "litrów"),
  },
  en: {
    person: (n) => (n === 1 ? "person" : "people"),
    litre: (n) => (n === 1 ? "litre" : "litres"),
  },
};

/** 2-4, 22-24 and so on take the "few" form; 12-14 do not. */
function plFew(n) {
  const last = Math.abs(n) % 10;
  const lastTwo = Math.abs(n) % 100;
  return last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14);
}

